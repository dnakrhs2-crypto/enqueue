//==============================================================================
class ManualWindow::Content : public juce::Component
{
public:
    Content()
    {
        tabs.setTabBarDepth (30);
        tabs.setOutline (0);
        tabs.setColour (juce::TabbedComponent::backgroundColourId, Palette::panel);

        for (const auto& section : ManualWindow::sections())
        {
            auto* page = new juce::TextEditor();
            page->setMultiLine (true, true);
            page->setReadOnly (true);
            page->setCaretVisible (false);
            page->setScrollbarsShown (true);
            page->setFont (juce::Font (juce::FontOptions (14.5f)));
            page->setColour (juce::TextEditor::backgroundColourId, Palette::background);
            page->setColour (juce::TextEditor::textColourId, Palette::text);
            page->setColour (juce::TextEditor::outlineColourId, juce::Colours::transparentBlack);
            page->setColour (juce::TextEditor::focusedOutlineColourId, juce::Colours::transparentBlack);
            page->setIndents (14, 12);
            page->setText (ko (section.text), false);
            page->setLineSpacing (1.25f);
            page->moveCaretToTop (false);   // setText leaves the view scrolled past the first lines
            tabs.addTab (ko (section.title), Palette::panel, page, true);   // the tab owns the page
        }

        addAndMakeVisible (tabs);
        setSize (960, 720);
    }

    void showSection (int index)
    {
        if (index >= 0 && index < tabs.getNumTabs())
            tabs.setCurrentTabIndex (index);
    }

    void resized() override
    {
        tabs.setBounds (getLocalBounds());
    }

    void paint (juce::Graphics& g) override
    {
        g.fillAll (Palette::background);
    }

private:
    juce::TabbedComponent tabs { juce::TabbedButtonBar::TabsAtTop };   // Korean tab names stay horizontal
};

//==============================================================================
ManualWindow::ManualWindow()
    : DocumentWindow (ko ("GoCue 사용 설명서"), Palette::background, DocumentWindow::allButtons)
{
    setUsingNativeTitleBar (true);
    auto* c = new Content();
    content = c;
    setContentOwned (c, true);
    setResizable (true, false);
    setResizeLimits (640, 420, 10000, 10000);
    centreWithSize (getWidth(), getHeight());
}

ManualWindow::~ManualWindow()
{
    clearContentComponent();
}

void ManualWindow::open (int sectionIndex)
{
    if (content != nullptr)
        content->showSection (sectionIndex);

    setVisible (true);
    toFront (true);
}

void ManualWindow::closeButtonPressed()
{
    setVisible (false);   // kept: reopening is instant and the tab stays where it was
}

